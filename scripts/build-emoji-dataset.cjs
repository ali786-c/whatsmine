/**
 * Builds resources/ai/emoji_dataset.php from emojibase-data (Unicode CLDR).
 *
 * Why: the AI engine must understand EVERY emoji, not a hand-curated subset.
 * emojibase ships the full CLDR annotation set — label + tags + group for
 * ~1950 emoji. This script converts it to a flat PHP map the EmojiEngine
 * merges under its curated customer-service overrides.
 *
 * Run: npm run emoji:build   (also wired as postinstall so a fresh npm
 * install keeps the dataset in sync with the package version).
 */
const fs = require('fs');
const path = require('path');

const data = require('../node_modules/emojibase-data/en/data.json');

const GROUPS = [
  'smileys-emotion',   // 0
  'people-body',       // 1
  'component',         // 2
  'animals-nature',    // 3
  'food-drink',        // 4
  'travel-places',     // 5
  'activities',        // 6
  'objects',           // 7
  'symbols',           // 8
  'flags',             // 9
];

// CLDR labels that are noise for retrieval — regional indicators, plain
// digits/letters, skin-tone variants of the same pictograph, component pieces.
const SKIP_LABELS = /^regional indicator|^white (large|medium|small) square|^black (large|medium|small) square|skin tone|^keycap/;

const entries = {};
let skipped = 0;

for (const e of data) {
    if (!e.label || (e.group === undefined && !e.tags?.length)) {
        skipped++;
        continue;
    }
    if (SKIP_LABELS.test(e.label)) {
        skipped++;
        continue;
    }
    if (e.group === 2) { // component (skin tones, ZWJ pieces)
        skipped++;
        continue;
    }

    const tags = [...new Set([
        ...(e.tags ?? []),
        ...e.label.split(/[\s,-]+/).filter(w => w.length > 2),
    ])]
        .map(t => t.toLowerCase())
        .filter(t => t.length > 1 && t.length <= 24)
        .slice(0, 10);

    entries[e.emoji] = [
        e.label.toLowerCase(),
        tags,
        GROUPS[e.group] ?? null,
    ];
}

const outDir = path.join(__dirname, '..', 'resources', 'ai');
fs.mkdirSync(outDir, { recursive: true });

const php = [
    '<?php',
    '',
    '/* AUTO-GENERATED by scripts/build-emoji-dataset.cjs — do not edit.',
    ' * Source: emojibase-data (Unicode CLDR annotations), ' + Object.keys(entries).length + ' emoji.',
    ' * Regenerate with: npm run emoji:build */',
    '',
    'return [',
];

for (const [unicode, [label, tags, group]] of Object.entries(entries)) {
    // Key MUST be double-quoted in the emitted PHP — single quotes would keep
    // the \\u{...} escapes as literal text instead of codepoints.
    const u = Array.from(unicode).map(c => '\\u{' + c.codePointAt(0).toString(16) + '}').join('');
    const tagList = tags.length ? "['" + tags.join("', '") + "']" : '[]';
    php.push(`    "${u}" => ['${label.replace(/'/g, "\\'")}', ${tagList}, ${group ? `'${group}'` : 'null'}],`);
}

php.push('];', '');

fs.writeFileSync(path.join(outDir, 'emoji_dataset.php'), php.join('\n'));
console.log(`Built resources/ai/emoji_dataset.php (${Object.keys(entries).length} emoji, ${skipped} skipped)`);
