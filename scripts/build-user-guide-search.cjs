#!/usr/bin/env node
/**
 * Builds docs/user-guide/assets/search-index.js from the static HTML pages
 * in docs/user-guide/. Pure Node, no dependencies.
 *
 * Usage: node scripts/build-user-guide-search.js
 * Run after adding/editing any user-guide HTML page.
 */
const fs = require('fs');
const path = require('path');

const DIR = path.join(__dirname, '..', 'docs', 'user-guide');
const OUT = path.join(DIR, 'assets', 'search-index.js');

const PAGES = [
    'getting-started.html',
    'inbox.html',
    'whatsapp.html',
    'instagram.html',
    'ai-chatbots.html',
    'automations.html',
    'campaigns.html',
    'contacts.html',
    'ecommerce.html',
    'social-media.html',
    'reports.html',
    'team-billing.html',
    'settings.html',
    'faq.html',
];

function stripTags(html) {
    return html
        .replace(/<style[\s\S]*?<\/style>/gi, ' ')
        .replace(/<script[\s\S]*?<\/script>/gi, ' ')
        .replace(/<[^>]+>/g, ' ')
        .replace(/&nbsp;/g, ' ')
        .replace(/&amp;/g, '&')
        .replace(/&lt;/g, '<')
        .replace(/&gt;/g, '>')
        .replace(/&#39;|&apos;/g, "'")
        .replace(/&quot;/g, '"')
        .replace(/&rarr;|&larr;/g, ' ')
        .replace(/\s+/g, ' ')
        .trim();
}

function decode(s) {
    return s.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
        .replace(/&#39;|&apos;/g, "'").replace(/&quot;/g, '"');
}

function extractSections(raw, file) {
    // Page title
    const titleMatch = raw.match(/<title>([^<]+)<\/title>/i);
    let pageTitle = titleMatch ? titleMatch[1].replace(/\s*— WhatsMine User Guide\s*/i, '').trim() : file;
    const h1Match = raw.match(/<h1[^>]*>([\s\S]*?)<\/h1>/i);
    if (h1Match) pageTitle = stripTags(h1Match[1]);
    const leadMatch = raw.match(/<p class="page-lead">([\s\S]*?)<\/p>/i);

    const sections = [{ t: pageTitle, b: leadMatch ? stripTags(leadMatch[1]) : '' }];

    // Split on <h2 id="...">
    const h2Regex = /<h2 id="([^"]+)"[^>]*>([\s\S]*?)<\/h2>/gi;
    const marks = [];
    let m;
    while ((m = h2Regex.exec(raw)) !== null) {
        marks.push({ id: m[1], title: stripTags(m[2]), index: m.index + m[0].length });
    }
    for (let i = 0; i < marks.length; i++) {
        const end = i + 1 < marks.length
            ? raw.lastIndexOf('<h2', marks[i + 1].index)
            : raw.lastIndexOf('<nav class="pager"');
        const chunk = raw.slice(marks[i].index, end > marks[i].index ? end : undefined);
        sections.push({ t: pageTitle + ' — ' + marks[i].title, b: stripTags(chunk).slice(0, 3000) });
    }

    // FAQ summaries (details/summary) — index each question
    const faqRegex = /<summary>([\s\S]*?)<\/summary>([\s\S]*?)(?=<details|<\/details>|$)/gi;
    while ((m = faqRegex.exec(raw)) !== null) {
        sections.push({ t: pageTitle + ' — FAQ: ' + stripTags(m[1]), b: stripTags(m[2]).slice(0, 1500) });
    }

    return sections;
}

const index = [];
for (const file of PAGES) {
    const p = path.join(DIR, file);
    if (!fs.existsSync(p)) {
        console.warn('  ! missing page (skipped): ' + file);
        continue;
    }
    const raw = fs.readFileSync(p, 'utf8');
    index.push({ file, title: extractSections(raw, file)[0].t, sections: extractSections(raw, file) });
}

const js = '/* Auto-generated by scripts/build-user-guide-search.js — do not edit by hand. */\n'
    + 'window.DOCS_SEARCH_INDEX = ' + JSON.stringify(index, null, 0) + ';\n';

fs.writeFileSync(OUT, js, 'utf8');
console.log('✔ search index written: docs/user-guide/assets/search-index.js (' + index.length + ' pages, '
    + index.reduce((n, p) => n + p.sections.length, 0) + ' sections)');
